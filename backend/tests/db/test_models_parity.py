"""models.py and the migrations describe the same database.

No single check sees everything, so three complementary ones are used:

1. ``alembic check`` (Alembic's autogenerate comparison) on the migrated schema must report
   nothing. It compares tables, columns, types, nullability, server defaults, foreign keys,
   unique constraints and ordinary indexes. It CANNOT see CHECK constraints, EXCLUDE
   constraints or an index's access method and operator classes (the trigram GIN indexes):
   altering any of those leaves its report empty. A test below pins that blind spot, and will
   fail if a future Alembic closes it, so this paragraph cannot silently go stale.
2. The catalog built by the migrations is compared with the catalog built by
   ``metadata.create_all()`` from the models, as PostgreSQL itself stores and normalises it
   (CHECK expressions, the EXCLUDE definition, index definitions with their operator classes
   and sort order, defaults, identity). That covers everything in 1, plus what 1 cannot see.
   Both comparisons are shown to fail on deliberate drift.
3. The items the SPEC names are asserted directly against the catalog, independently of
   models.py, so that the models and the migrations cannot drift from the SPEC together.
"""

from collections.abc import Callable, Iterator, Sequence
from contextlib import contextmanager

import psycopg
import pytest
from alembic.autogenerate import compare_metadata
from alembic.config import Config
from alembic.runtime.migration import MigrationContext
from sqlalchemy import Connection, Engine, create_engine, pool

from alembic import command
from app.models import Base
from tests.db.catalog import SchemaSnapshot, schema_snapshot
from tests.db.support import connect

ConfigFactory = Callable[[str], Config]

# Drift that Alembic's comparison reports: label -> (statements applying it, operations reported).
DETECTED_BY_ALEMBIC: dict[str, tuple[tuple[str, ...], list[str]]] = {
    "extra column": (("ALTER TABLE medicines ADD COLUMN extra text",), ["remove_column"]),
    "nullability changed": (
        ("ALTER TABLE medicines ALTER COLUMN form DROP NOT NULL",),
        ["modify_nullable"],
    ),
    "type changed": (
        ("ALTER TABLE medicines ALTER COLUMN code TYPE varchar(10)",),
        ["modify_type"],
    ),
    "server default dropped": (
        ("ALTER TABLE medicines ALTER COLUMN is_active DROP DEFAULT",),
        ["modify_default"],
    ),
    "identity ALWAYS changed to BY DEFAULT": (
        ("ALTER TABLE medicines ALTER COLUMN id SET GENERATED BY DEFAULT",),
        ["modify_default"],
    ),
    "foreign key dropped": (
        ("ALTER TABLE dispenses DROP CONSTRAINT fk_dispenses_medicine_id",),
        ["add_fk"],
    ),
    "composite foreign key dropped": (
        ("ALTER TABLE dispenses DROP CONSTRAINT fk_dispenses_rule_id_medicine_id",),
        ["add_fk"],
    ),
    "unique constraint dropped": (
        ("ALTER TABLE medicines DROP CONSTRAINT uq_medicines_code",),
        ["add_constraint"],
    ),
    "index dropped": (("DROP INDEX ix_medicines_name_code",), ["add_index"]),
    "index changed from DESC to ASC": (
        (
            "DROP INDEX ix_dispenses_time",
            "CREATE INDEX ix_dispenses_time ON dispenses (dispensed_at, id)",
        ),
        ["add_index", "remove_index"],
    ),
}

# Drift that Alembic's comparison does not report at all: label -> statements applying it.
INVISIBLE_TO_ALEMBIC: dict[str, tuple[str, ...]] = {
    "CHECK constraint dropped": (
        "ALTER TABLE medicines DROP CONSTRAINT ck_medicines_strength_value_positive",
    ),
    "CHECK constraint changed": (
        "ALTER TABLE medicines DROP CONSTRAINT ck_medicines_strength_value_positive",
        (
            "ALTER TABLE medicines ADD CONSTRAINT ck_medicines_strength_value_positive"
            " CHECK (strength_value >= 0)"
        ),
    ),
    "EXCLUDE constraint dropped": (
        "ALTER TABLE formulary_rules DROP CONSTRAINT ex_formulary_rules_no_overlap",
    ),
    "trigram index replaced by a plain btree": (
        "DROP INDEX ix_medicines_name_trgm",
        "CREATE INDEX ix_medicines_name_trgm ON medicines (name)",
    ),
}


@pytest.fixture
def migrated_engine(scratch_database: str, alembic_config: ConfigFactory) -> Iterator[Engine]:
    command.upgrade(alembic_config(scratch_database), "head")
    engine = create_engine(scratch_database, poolclass=pool.NullPool)
    yield engine
    engine.dispose()


@pytest.fixture
def models_snapshot(scratch_database_factory: Callable[[], str]) -> Iterator[SchemaSnapshot]:
    """The catalog PostgreSQL ends up with when the schema is created from the models."""
    url = scratch_database_factory()
    with connect(url, autocommit=True) as db:
        db.execute("CREATE EXTENSION btree_gist")
        db.execute("CREATE EXTENSION pg_trgm")
    engine = create_engine(url, poolclass=pool.NullPool)
    try:
        Base.metadata.create_all(engine)
        with engine.connect() as connection:
            yield schema_snapshot(connection)
    finally:
        engine.dispose()


@contextmanager
def drifted(engine: Engine, statements: Sequence[str]) -> Iterator[Connection]:
    """A connection on which the schema has been altered by ``statements``. The change is
    undone afterwards: DDL is transactional in PostgreSQL."""
    with engine.connect() as connection:
        transaction = connection.begin()
        try:
            for statement in statements:
                connection.exec_driver_sql(statement)
            yield connection
        finally:
            transaction.rollback()


def alembic_operations(connection: Connection) -> list[str]:
    """The operations autogenerate would emit, with the same options as alembic/env.py."""
    context = MigrationContext.configure(
        connection, opts={"compare_type": True, "compare_server_default": True}
    )
    names: list[str] = []
    for difference in compare_metadata(context, Base.metadata):
        names.extend(
            item[0] for item in (difference if isinstance(difference, list) else [difference])
        )
    return sorted(names)


# -- 1. Alembic's autogenerate comparison ---------------------------------------------------


def test_alembic_check_finds_no_difference_between_the_models_and_the_migrations(
    scratch_database: str, alembic_config: ConfigFactory
) -> None:
    config = alembic_config(scratch_database)
    command.upgrade(config, "head")

    command.check(config)  # raises if autogenerate would emit any operation


def test_alembic_comparison_detects_drift_in_what_it_can_compare(migrated_engine: Engine) -> None:
    observed: dict[str, list[str]] = {}
    for label, (statements, _) in DETECTED_BY_ALEMBIC.items():
        with drifted(migrated_engine, statements) as connection:
            observed[label] = alembic_operations(connection)

    assert observed == {label: expected for label, (_, expected) in DETECTED_BY_ALEMBIC.items()}


def test_alembic_comparison_is_blind_to_checks_exclusions_and_index_operator_classes(
    migrated_engine: Engine,
) -> None:
    observed: dict[str, list[str]] = {}
    for label, statements in INVISIBLE_TO_ALEMBIC.items():
        with drifted(migrated_engine, statements) as connection:
            observed[label] = alembic_operations(connection)

    assert observed == {label: [] for label in INVISIBLE_TO_ALEMBIC}


# -- 2. Catalog against catalog -------------------------------------------------------------


def test_catalog_built_by_the_migrations_equals_the_one_built_from_the_models(
    migrated_engine: Engine, models_snapshot: SchemaSnapshot
) -> None:
    with migrated_engine.connect() as connection:
        migrated = schema_snapshot(connection)

    assert migrated.keys() == models_snapshot.keys()
    for part, rows in migrated.items():
        assert rows == models_snapshot[part], part


def test_catalog_comparison_detects_every_drift_including_what_alembic_cannot_see(
    migrated_engine: Engine, models_snapshot: SchemaSnapshot
) -> None:
    drifts = {label: statements for label, (statements, _) in DETECTED_BY_ALEMBIC.items()}
    drifts |= INVISIBLE_TO_ALEMBIC

    undetected: list[str] = []
    for label, statements in drifts.items():
        with drifted(migrated_engine, statements) as connection:
            if schema_snapshot(connection) == models_snapshot:
                undetected.append(label)

    assert undetected == []


# -- 3. What the SPEC names, asserted directly against the catalog ---------------------------


def test_exclusion_constraint_forbids_overlapping_periods_of_one_medicine(
    db: psycopg.Connection,
) -> None:
    row = db.execute(
        "SELECT contype, pg_get_constraintdef(oid) FROM pg_constraint"
        " WHERE conrelid = 'formulary_rules'::regclass"
        " AND conname = 'ex_formulary_rules_no_overlap'"
    ).fetchone()

    assert row == (
        "x",
        (
            "EXCLUDE USING gist (medicine_id WITH =,"
            " daterange(effective_from, effective_to, '[)'::text) WITH &&)"
        ),
    )


def test_trigram_indexes_use_gin_with_the_trigram_operator_class(db: psycopg.Connection) -> None:
    rows = db.execute(
        "SELECT indexname, indexdef FROM pg_indexes"
        " WHERE indexname IN ('ix_medicines_name_trgm', 'ix_medicines_code_trgm')"
        " ORDER BY indexname"
    ).fetchall()

    assert rows == [
        (
            "ix_medicines_code_trgm",
            "CREATE INDEX ix_medicines_code_trgm ON public.medicines USING gin (code gin_trgm_ops)",
        ),
        (
            "ix_medicines_name_trgm",
            "CREATE INDEX ix_medicines_name_trgm ON public.medicines USING gin (name gin_trgm_ops)",
        ),
    ]


def test_dispenses_indexes_have_the_documented_columns_in_descending_order(
    db: psycopg.Connection,
) -> None:
    rows = db.execute(
        "SELECT indexname, indexdef FROM pg_indexes WHERE indexname IN"
        " ('ix_dispenses_patient_medicine_time', 'ix_dispenses_medicine_time', 'ix_dispenses_time')"
        " ORDER BY indexname"
    ).fetchall()

    assert rows == [
        (
            "ix_dispenses_medicine_time",
            (
                "CREATE INDEX ix_dispenses_medicine_time ON public.dispenses"
                " USING btree (medicine_id, dispensed_at DESC, id DESC)"
            ),
        ),
        (
            "ix_dispenses_patient_medicine_time",
            (
                "CREATE INDEX ix_dispenses_patient_medicine_time ON public.dispenses"
                " USING btree (patient_ref, medicine_id, dispensed_at DESC, id DESC)"
            ),
        ),
        (
            "ix_dispenses_time",
            (
                "CREATE INDEX ix_dispenses_time ON public.dispenses"
                " USING btree (dispensed_at DESC, id DESC)"
            ),
        ),
    ]


def test_required_extensions_are_installed(db: psycopg.Connection) -> None:
    installed = {name for (name,) in db.execute("SELECT extname FROM pg_extension")}

    assert {"btree_gist", "pg_trgm"} <= installed


def test_every_primary_key_is_an_identity_column_that_is_always_generated(
    db: psycopg.Connection,
) -> None:
    rows = db.execute(
        "SELECT c.relname, a.attidentity::text FROM pg_attribute a"
        " JOIN pg_class c ON c.oid = a.attrelid"
        " WHERE a.attname = 'id' AND c.relnamespace = 'public'::regnamespace AND c.relkind = 'r'"
        " AND c.relname <> 'alembic_version' ORDER BY c.relname"
    ).fetchall()

    # 'a' is GENERATED ALWAYS, 'd' would be GENERATED BY DEFAULT.
    assert rows == [
        ("dispense_attempts", "a"),
        ("dispenses", "a"),
        ("formulary_rules", "a"),
        ("medicines", "a"),
    ]
